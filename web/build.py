#!/usr/bin/env python3
"""Regenerate the static blog from entry-N/*.md source files.

Run this after writing or editing any concepts.md / exercise.md:

    python3 build.py

For each entry-N/*.md it writes a sibling entry-N/*.html (markdown embedded
inline, no fetch — works opened directly via file://) and regenerates
entries.js, which index.html uses to render the entry list.
"""
import base64
import html
import json
import re
from datetime import date
from pathlib import Path

WEB_DIR = Path(__file__).parent
TEMPLATE = (WEB_DIR / "_template.html").read_text()


SITE_URL = "https://softwaresystems.blog"


def extract_title(md_text: str, fallback: str) -> str:
    match = re.search(r"^#\s+(.+)$", md_text, re.MULTILINE)
    return match.group(1).strip() if match else fallback


def extract_description(md_text: str, title: str) -> str:
    body = re.sub(r"^#\s+.+$", "", md_text, count=1, flags=re.MULTILINE)
    for line in body.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or line.startswith("```"):
            continue
        line = re.sub(r"[`*_]", "", line)
        return (line[:157] + "...") if len(line) > 160 else line
    return f"{title} — from Systems & Software Concepts, a blog on software fundamentals and systems design by Leandro Dal Bo."


def render_page(md_path: Path, entry_dir: str) -> str:
    md_text = md_path.read_text()
    title = extract_title(md_text, md_path.stem.title())
    description = extract_description(md_text, title)
    b64 = base64.b64encode(md_text.encode("utf-8")).decode("ascii")
    url = f"{SITE_URL}/{entry_dir}/{md_path.stem}.html"
    page = (
        TEMPLATE.replace("{{TITLE}}", html.escape(title))
        .replace("{{DESCRIPTION}}", html.escape(description))
        .replace("{{URL}}", html.escape(url))
        .replace("{{MD_B64}}", b64)
    )
    md_path.with_suffix(".html").write_text(page)
    return title


def build_index():
    entries = []
    for entry_dir in sorted(
        WEB_DIR.glob("entry-*"),
        key=lambda p: (int(p.name.split("-")[1]), p.name),
    ):
        parts = entry_dir.name.split("-", 2)
        n = int(parts[1])
        label = f"Entry {n}" + (f" {parts[2]}" if len(parts) > 2 else "")
        concepts_md = entry_dir / "concepts.md"
        exercise_md = entry_dir / "exercise.md"
        if not concepts_md.exists():
            continue

        entry_date = date.fromtimestamp(concepts_md.stat().st_mtime).isoformat()
        entry = {
            "number": n,
            "label": label,
            "date": entry_date,
            "title": render_page(concepts_md, entry_dir.name),
            "concepts": f"{entry_dir.name}/concepts.html",
        }
        if exercise_md.exists():
            entry["exercise"] = {
                "title": render_page(exercise_md, entry_dir.name),
                "src": f"{entry_dir.name}/exercise.html",
            }
        entries.append(entry)

    js = "// Generated by build.py — do not edit by hand.\nconst entries = "
    js += json.dumps(entries, indent=2)
    js += ";\n"
    (WEB_DIR / "entries.js").write_text(js)
    return entries


if __name__ == "__main__":
    built = build_index()
    names = ", ".join(d["label"] for d in built)
    noun = "entry" if len(built) == 1 else "entries"
    print(f"Built {len(built)} {noun}: {names}")
